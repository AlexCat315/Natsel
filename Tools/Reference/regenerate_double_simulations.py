#!/usr/bin/env python3
"""Regenerate trajectory/contact fixtures from an independent Box3D double build.

Usage: python3 Tools/Reference/regenerate_double_simulations.py BOX3D_SOURCE DOUBLE_BUILD
Configure the reference build with BOX3D_DOUBLE_PRECISION=ON before running this script.
"""
import argparse
from pathlib import Path
import re
import subprocess
import tempfile

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("source", type=Path)
parser.add_argument("build", type=Path)
args = parser.parse_args()
source = args.source.resolve()
build = args.build.resolve()
cache = (build / "CMakeCache.txt").read_text()
if "BOX3D_DOUBLE_PRECISION:BOOL=ON" not in cache:
    parser.error("the reference library must be built with BOX3D_DOUBLE_PRECISION=ON")
root = Path(__file__).resolve().parents[2]
fixtures = {
    "compound": "Compound/SimulationReference.swift",
    "height": "HeightField/TerrainReference.swift",
    "mesh": "Mesh/ContactReference.swift",
}
with tempfile.TemporaryDirectory(prefix="natsel-double-reference-") as temporary:
    for scene, destination in fixtures.items():
        executable = Path(temporary) / scene
        generator = root / "Tools/Reference" / f"{scene}_simulation.c"
        subprocess.run([
            "clang", "-O2", "-DNDEBUG", "-DBOX3D_DOUBLE_PRECISION", "-ffp-contract=off",
            "-I", str(source / "src"), "-I", str(source / "include"), str(generator),
            str(build / "src/libbox3d.a"), "-o", str(executable),
        ], check=True)
        output = subprocess.check_output([str(executable)], text=True)
        records = {}
        for line in output.splitlines():
            match = re.fullmatch(r"scenario (\d+) step (\d+) bodies (0x\w+) contacts (0x\w+)", line)
            if match:
                records.setdefault(int(match[1]), []).append((int(match[2]), match[3], match[4]))
        expected_count = 108 if scene == "compound" else 54 if scene == "height" else 27
        if sorted(records) != list(range(expected_count)) or any(
            [step for step, _, _ in rows] != [30, 60, 90, 120, 150, 180] for rows in records.values()
        ):
            raise RuntimeError(f"incomplete reference output for {scene}")
        lines = [f"// Generated by Tools/Reference/{scene}_simulation.c with BOX3D_DOUBLE_PRECISION; cumulative hashes every 30 steps.",
                 f"let {scene}SimulationReference: [[(body: UInt64, contact: UInt64)]] = ["]
        for rows in records.values():
            lines.append("    [")
            lines.extend(f"        ({body}, {contact})," for _, body, contact in rows)
            lines.append("    ],")
        lines.append("]")
        target = root / "Tests/NatselTests/Collision" / destination
        content = "\n".join(lines) + "\n"
        if target.read_text() != content:
            target.write_text(content)
