impl World {
    /// The number of awake bodies. These are bodies that are in the awake solver set, which
    /// includes dynamic and kinematic bodies that have not gone to sleep.
    pub fn awake_body_count(&self) -> i32 {
        self.solver_sets[SetType::AwakeSet.raw_value() as usize].body_sims.len() as i32
    }

    /// Body move events generated by the most recent step. The array is empty when no body moved.
    pub fn body_events(&self) -> &[BodyMoveEvent] {
        &self.body_move_events
    }

    /// Sensor begin/end touch events generated by the most recent step, in packed layout.
    pub fn sensor_event_buffers(&self) -> SensorEvents {
        // Swift built the packed view from `sensorBeginEvents` and `sensorEndEvents.published`;
        // the owned Rust `SensorEvents` copies the same two lists in the same order.
        SensorEvents {
            begin_events: self.sensor_begin_events.clone(),
            end_events: self.sensor_end_events.published().to_vec(),
        }
    }

    /// Contact begin/end/hit events generated by the most recent step.
    pub fn contact_events(&self) -> ContactEvents {
        // Same begin/published-end/hit sources as Swift's nested `withUnsafeBufferPointer`s.
        ContactEvents {
            begin_events: self.contact_begin_events.clone(),
            end_events: self.contact_end_events.published().to_vec(),
            hit_events: self.contact_hit_events.clone(),
        }
    }

    /// Transient CCD impacts from the last step, including impacts resolved before a persistent
    /// contact exists. Requested by contact/hit event flags and independent of hitEventThreshold.
    pub fn continuous_impacts(&self) -> &[ContactHitEvent] {
        &self.continuous_impact_events
    }

    /// The number of contacts in the world that are touching.
    pub fn touching_contact_count(&self) -> i32 {
        // Swift's `contacts.reduce(0)` accumulates in contact id order; keep the fold.
        self.contacts.iter().fold(0i32, |count, contact| {
            count + if (contact.flags & ContactFlags::TOUCHING.0) != 0 { 1 } else { 0 }
        })
    }
}

impl World {
    /// Number of live bodies in the world.
    pub fn body_count(&self) -> i32 {
        self.body_id_pool.id_count()
    }

    /// Number of live contacts in the world.
    pub fn contact_count(&self) -> i32 {
        self.contact_id_pool.id_count()
    }

    /// Number of live joints in the world.
    pub fn joint_count(&self) -> i32 {
        self.joint_id_pool.id_count()
    }

    /// Number of hulls currently interned in the world database.
    pub fn hull_database_count(&self) -> usize {
        self.hull_database.count()
    }

    /// Number of live compound shapes. The broad-phase uses this to pick between the fast and
    /// slow pair paths, so a leak here is a permanent performance regression.
    pub fn compound_shape_count_value(&self) -> i32 {
        self.compound_shape_count
    }

    /// True while the body id refers to a live body.
    pub fn body_is_valid(&self, body_id: BodyID) -> bool {
        let index = body_id.index1 - 1;
        if index < 0 || index as usize >= self.bodies.len() {
            return false;
        }
        let body = &self.bodies[index as usize];
        body.id != b3::NULL_INDEX && body.generation == body_id.generation
    }
}

impl World {
    /// Diagnostic counters for the world.
    pub fn counters(&self) -> Counters {
        let mut counters = Counters::default();
        counters.body_count = self.body_count();
        counters.shape_count = self.shapes.len() as i32;
        counters.contact_count = self.contact_count();
        counters.joint_count = self.joint_count();
        counters.island_count = self.islands.len() as i32;
        counters.sat_call_count = self.sat_call_count;
        counters.sat_cache_hit_count = self.sat_cache_hit_count;
        counters.recycled_contact_count = self.task_contexts[0].recycled_contact_count;
        counters.static_tree_height =
            self.broad_phase.trees[BodyType::StaticBody as usize].height();
        counters.tree_height = self.broad_phase.trees[BodyType::DynamicBody as usize].height();

        // Per-color constraint counts and the awake non-touching contact total.
        counters.awake_contact_count = 0;
        for i in 0..b3::GRAPH_COLOR_COUNT as usize {
            let color = &self.constraint_graph.colors[i];
            let color_contact_count = color.convex_contacts.len() + color.contacts.len();
            counters.color_counts[i] = (color_contact_count + color.joint_sims.len()) as i32;
            counters.awake_contact_count += color_contact_count as i32;
        }
        counters.awake_contact_count +=
            self.solver_sets[SetType::AwakeSet.raw_value() as usize].contact_indices.len() as i32;

        counters
    }
}

impl World {
    /// Resolve the user material id at a hit point. Mesh and height-field shapes use the manifold
    /// point's triangle index; compound shapes resolve through the participating child.
    pub(crate) fn shape_user_material_id(
        &self,
        shape: &Shape,
        child_index: i32,
        triangle_index: i32,
    ) -> u64 {
        if shape.material_count() == 0 {
            return 0;
        }

        let mut material_index: i32 = 0;

        match &shape.geometry {
            ShapeGeometry::Mesh(mesh) => {
                if let Some(data) = mesh.data.as_ref() {
                    material_index = data.material_indices()[triangle_index as usize] as i32;
                }
            }

            ShapeGeometry::HeightField(field) => {
                material_index = field.material(triangle_index);
            }

            ShapeGeometry::Compound(compound) => {
                let child = compound.child(child_index as usize);
                // Swift's `if case .mesh, let data` fell through to the else when the child was a
                // mesh without shared data as well, so both paths index material 0.
                match &child.geometry {
                    CompoundChildGeometry::Mesh(mesh) => match mesh.data.as_ref() {
                        Some(data) => {
                            let mesh_material_index =
                                data.material_indices()[triangle_index as usize] as i32;
                            b3_assert(
                                mesh_material_index >= 0
                                    && mesh_material_index
                                        < child.material_indices.len() as i32,
                            );
                            material_index =
                                child.material_indices[mesh_material_index as usize] as i32;
                        }

                        None => {
                            material_index = child.material_indices[0] as i32;
                        }
                    },

                    _ => {
                        material_index = child.material_indices[0] as i32;
                    }
                }
            }

            _ => {}
        }

        material_index = clamp_int(material_index, 0, shape.material_count() - 1);
        shape.material(material_index).user_material_id
    }

    /// Emit contact hit events for the step.
    pub(crate) fn emit_contact_hit_events(&mut self) {
        let threshold = self.hit_event_threshold;

        // Iterate contacts in id order so events are deterministic. Contacts are read in place: a
        // copy retains three arrays.
        //
        // Swift appended `contactHitEvents` from inside the same pass because the world is a
        // reference class; Rust reaches the append as the disjoint field
        // `self.contact_hit_events.push` after the shared reads of the iteration, which keeps the
        // queue order identical.
        for contact_id in 0..self.contacts.len() as i32 {
            let contact = &self.contacts[contact_id as usize];
            if (contact.flags & ContactFlags::SIM_ENABLE_HIT_EVENT.0) == 0 {
                continue;
            }
            if contact.contact_id == b3::NULL_INDEX
                || contact.set_index != SetType::AwakeSet.raw_value()
                || contact.color_index == b3::NULL_INDEX
            {
                continue;
            }

            let shape_index_a = contact.shape_id_a as usize;
            let shape_index_b = contact.shape_id_b as usize;
            let mid_center = lerp_position(
                self.body_center(self.shapes[shape_index_a].body_id),
                self.body_center(self.shapes[shape_index_b].body_id),
                0.5,
            );

            let mut event = ContactHitEvent::default();
            event.approach_speed = threshold;

            let mut found = false;
            let mut triangle_index: i32 = 0;
            let manifolds = contact.manifolds();

            for manifold_index in 0..contact.manifold_count as usize {
                let manifold: &Manifold = manifolds.get(manifold_index);
                for point_index in 0..manifold.point_count as usize {
                    let mp = manifold.points[point_index];
                    let approach_speed = -mp.normal_velocity;

                    // Check the total impulse because the point may be speculative and not colliding.
                    if approach_speed > event.approach_speed && mp.total_normal_impulse > 0.0 {
                        event.approach_speed = approach_speed;
                        event.point = offset_pos(mid_center, lerp(mp.anchor_a, mp.anchor_b, 0.5));
                        event.normal = manifold.normal;
                        triangle_index = mp.triangle_index;
                        found = true;
                    }
                }
            }

            if !found {
                continue;
            }

            event.shape_id_a = ShapeID::new(
                shape_index_a as i32 + 1,
                self.world_id,
                self.shapes[shape_index_a].generation,
            );
            event.shape_id_b = ShapeID::new(
                shape_index_b as i32 + 1,
                self.world_id,
                self.shapes[shape_index_b].generation,
            );
            event.contact_id =
                ContactID::new(contact.contact_id + 1, self.world_id, contact.generation);

            // shapeB is never a compound today, so the child index is irrelevant for it.
            event.user_material_id_a = self.shape_user_material_id(
                &self.shapes[shape_index_a],
                contact.child_index,
                triangle_index,
            );
            event.user_material_id_b = self.shape_user_material_id(
                &self.shapes[shape_index_b],
                0,
                triangle_index,
            );

            self.contact_hit_events.push(event);
        }
    }

    fn body_center(&self, body_id: i32) -> Pos {
        let set_index = self.bodies[body_id as usize].set_index as usize;
        let local_index = self.bodies[body_id as usize].local_index as usize;
        self.solver_sets[set_index].body_sims[local_index].center
    }
}

// MARK: - World tuning

impl World {
    /// Set the contact softness and the maximum push-out speed in one call.
    pub fn set_contact_tuning(&mut self, hertz: f32, damping_ratio: f32, contact_speed: f32) {
        self.contact_hertz = hertz;
        self.contact_damping_ratio = damping_ratio;
        self.contact_speed = clamp_float(contact_speed, 0.0, f32::MAX);
    }

    /// Number of bodies in the awake solver set.
    pub fn awake_body_count_public(&self) -> i32 {
        self.awake_body_count()
    }

    /// Profiling data for the most recent step.
    pub fn profile_data(&self) -> Profile {
        self.profile
    }

    /// True while sleeping is enabled for the world.
    pub fn is_sleeping_enabled(&self) -> bool {
        self.enable_sleep
    }

    /// True while warm starting is enabled.
    pub fn is_warm_starting_enabled(&self) -> bool {
        self.enable_warm_starting
    }

    /// True while continuous collision is enabled.
    pub fn is_continuous_enabled(&self) -> bool {
        self.enable_continuous
    }

    /// Enable or disable sleeping for the whole world.
    pub fn enable_sleeping(&mut self, enable: bool) {
        self.enable_sleep = enable;
    }

    /// Enable or disable warm starting.
    pub fn enable_warm_starting(&mut self, enable: bool) {
        self.enable_warm_starting = enable;
    }

    /// Enable or disable continuous collision.
    pub fn enable_continuous(&mut self, enable: bool) {
        self.enable_continuous = enable;
    }
}
