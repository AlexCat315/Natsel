//! World event accessors and counters.
//!
//! Translated from `Sources/Natsel/Simulation/WorldEvents.swift`.
//!
//! Foreign vocabulary assumed from sibling modules (translated concurrently; see MIGRATION.md
//! "Shared simulation vocabulary"):
//! - `crate::simulation::shape_creation::HullDatabase` (`ShapeCreation.swift`): the
//!   `count` property, ported as `hull_database.count()` (Swift `hullDatabase.count`).
//! - `crate::simulation::world_queries` (`WorldQueries.swift`, same batch): `body_center` below
//!   reads the same solver-set storage; no function from that file is called here.
//!
//! Swift's `sensorEventBuffers()`/`contactEvents()` returned `SensorEvents`/`ContactEvents`
//! wrapping `UnsafeBufferPointer` views into the world's storage. The landed Rust
//! `types::events::{SensorEvents, ContactEvents}` own `Vec`s, so those two accessors copy the
//! event lists instead of borrowing them. The contents, queue order (begin before the published
//! end buffer), and per-step snapshots are unchanged; only the zero-copy property is lost.
//! Likewise Swift's `[BodyMoveEvent]`/`[ContactHitEvent]` array returns become borrowed slices.

